    def save_user_message(self, text):
        self.history_collection.insert_one({'role': 'user', 'content': text})

    def save_assistant_message(self, text):
        self.history_collection.insert_one({'role': 'assistant', 'content': text})

    def get_saved_history(self):
        return self.history_collection.find().sort("_id", 1)

    def get_ai_response_sync(self, user_text="", is_hidden_prompt=False):
        """Синхронный метод генерации, принимающий живой текст из раздвоенного потока"""
        formatted_prompt = f"<|im_start|>system\n{self.system_prompt}<|im_end|>\n"
        
        # Подтягиваем контекст прошлых сообщений из MongoDB (БЕЗ учета текущего, так как мы передаем его ниже!)
        recent_history = self.history_collection.find().sort("_id", -1).limit(14)
        history_list = list(recent_history)[::-1]
        
        for msg in history_list:
            if "[EXIT]" in msg['content']: continue
            role_tag = "user" if msg['role'] == 'user' else "assistant"
            formatted_prompt += f"<|im_start|>{role_tag}\n{msg['content']}<|im_end|>\n"
            
        # 🔥 ВСТРАИВАЕМ ЖИВОЙ ТЕКСТ ПОЛЬЗОВАТЕЛЯ ИЗ РАЗДВОЕННОГО ПОТОКА НАПРЯМУЮ!
        if user_text:
            formatted_prompt += f"<|im_start|>user\n{user_text}<|im_end|>\n"
            
        if is_hidden_prompt:
            formatted_prompt += "<|im_start|>user\nПодсказка: Ты немного заскучала. Напиши ОДНУ очень короткую и милую фразу хозяину.<|im_end|>\n"
            
        formatted_prompt += "<|im_start|>assistant\n"

        print("[ИИ МОЗГ] Начинаем инференс на RTX 3060...")
        output = self.llm(
            formatted_prompt,
            max_tokens=160,
            stop=["<|im_end|>", "<|eot_id|>", "user\n", "assistant\n", "</s>"],
            temperature=0.7,
            top_p=0.9
        )
        
        reply = output['choices'][0]['text'].strip() # Гарантируем извлечение первого элемента списка
        return reply
